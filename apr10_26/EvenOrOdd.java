public class EvenOrOdd{
       public static void EvenOrOdd(int a ){
             if (a%2 == 0){
                 System.out.println("This num is even");
             }
             else{
                System.out.println("This num is odd");
             }
    }
       public static void main(String[] args){
              EvenOrOdd(7);
              EvenOrOdd(10);
            }
}

