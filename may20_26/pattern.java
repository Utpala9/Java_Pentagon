package pattern;

public class pattern{

    public static void main(String[]args){
       int row = 5;
       int col =5;
       char ch ='A';
       for (int i=1;i<=row;i++){
           for (int j=1;j<=col;j++){
               System.out.print(ch+"");
           }
           System.out.println();
       }
    }
    
}
